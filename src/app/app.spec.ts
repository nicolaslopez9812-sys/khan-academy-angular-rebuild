import { TestBed } from '@angular/core/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    const app = fixture.componentInstance;
    expect(app).toBeTruthy();
  });

  it('should render the Khan Academy landing sections', async () => {
    const fixture = TestBed.createComponent(App);
    fixture.detectChanges();
    await fixture.whenStable();

    const compiled = fixture.nativeElement as HTMLElement;
    expect(compiled.querySelector('h1')?.textContent).toContain('Khan Academy aumenta los puntajes');
    expect(compiled.querySelectorAll('.course-card').length).toBe(6);
    expect(compiled.querySelectorAll('.signup__option').length).toBe(3);
    expect(compiled.querySelector('.footer')).toBeTruthy();
  });
});
